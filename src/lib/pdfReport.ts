import type { ScanResult } from "./api";

// Lightweight, dependency-free PDF report generator using window.print on a styled HTML doc.
export function downloadPdfReport(result: ScanResult, imagePreview: string | null) {
  const w = window.open("", "_blank", "width=900,height=1200");
  if (!w) return;

  w.document.write(`
<!doctype html>
<html>
<head>
<title>DermAI Report ${result.id}</title>
<style>
  * { box-sizing: border-box; }
  body { font-family: 'Helvetica', Arial, sans-serif; margin: 40px; color: #0b0f12; background: #fff; }
  .h { display:flex; justify-content:space-between; align-items:center; border-bottom: 3px solid #0b0f12; padding-bottom: 12px; margin-bottom: 20px; }
  .h h1 { margin:0; font-size: 24px; letter-spacing: 2px; }
  .h .id { font-family: monospace; font-size: 11px; color: #555; }
  .grid { display:grid; grid-template-columns: 1fr 1fr; gap: 20px; margin-bottom: 20px; }
  .card { border:1px solid #ddd; padding: 14px; border-radius: 4px; }
  .label { font-size: 10px; letter-spacing: 1.5px; color:#666; text-transform: uppercase; margin-bottom: 4px; }
  .val { font-size: 18px; font-weight: bold; }
  .risk-Critical { color:#d11; }
  .risk-High { color:#e80; }
  .risk-Low { color:#1a8; }
  ul { padding-left: 18px; }
  li { margin: 6px 0; font-size: 13px; }
  img { max-width: 100%; border: 1px solid #ddd; border-radius: 4px; }
  .rec { background:#f6f6f6; border-left: 4px solid #0b0f12; padding: 12px; margin-top: 12px; font-size: 13px; }
  .footer { margin-top: 30px; font-size: 10px; color:#888; text-align:center; border-top:1px solid #ddd; padding-top:10px; }
</style>
</head>
<body>
  <div class="h">
    <h1>DERM<span style="color:#0aa">AI</span> · CLINICAL REPORT</h1>
    <div>
      <div class="id">${result.id}</div>
      <div class="id">${new Date(result.timestamp).toLocaleString()}</div>
    </div>
  </div>

  <div class="grid">
    <div class="card">
      <div class="label">Classification</div>
      <div class="val">${result.classification}</div>
      <div class="label" style="margin-top:12px">Confidence</div>
      <div class="val">${result.confidence.toFixed(2)}%</div>
      <div class="label" style="margin-top:12px">Risk Level</div>
      <div class="val risk-${result.risk}">${result.risk.toUpperCase()}</div>
    </div>
    <div class="card">
      ${imagePreview ? `<img src="${imagePreview}" alt="Lesion" />` : '<div style="color:#888;font-size:12px">No image attached</div>'}
    </div>
  </div>

  <div class="card">
    <div class="label">Clinical Insights</div>
    <ul>${result.insights.map((i) => `<li>${i}</li>`).join("")}</ul>
    <div class="rec"><strong>Recommendation:</strong> ${result.recommendation}</div>
  </div>

  <div class="footer">
    Generated by DermAI (MobileNetV2) · Research prototype. This report is decision-support only and does not replace clinical judgment.
  </div>

  <script>window.onload = () => { window.print(); };</script>
</body>
</html>
  `);
  w.document.close();
}
